namespace LongLeap.Tools
{
    /// <summary>
    /// Профиль устройства: где запущена игра и чем управляют. Две оси сведены в одно
    /// значение, чтобы по нему можно было выбирать конфиг (<c>switch</c>, словарь,
    /// поле ассета) без пары флагов.
    /// </summary>
    public enum DeviceProfile
    {
        /// <summary>Нативная сборка для ПК (или редактор): клавиатура и мышь.</summary>
        Desktop = 0,

        /// <summary>Нативная мобильная сборка или планшет: управление пальцами.</summary>
        Mobile = 1,

        /// <summary>Браузер на ПК (WebGL): клавиатура и мышь.</summary>
        WebDesktop = 2,

        /// <summary>Браузер на телефоне или планшете (WebGL): управление пальцами.</summary>
        WebMobile = 3,
    }
}
