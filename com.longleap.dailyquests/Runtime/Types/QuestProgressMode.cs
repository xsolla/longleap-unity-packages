namespace LongLeap.DailyQuests
{
    /// <summary>Как значение стата превращается в прогресс цели.</summary>
    public enum QuestProgressMode
    {
        /// <summary>
        /// Насколько стат вырос с момента выдачи квеста: «прогринди 50 раз»
        /// считает гринды за этот период, а не за всю жизнь. Для накопительных
        /// статов (Accumulate). По умолчанию.
        /// </summary>
        Delta = 0,

        /// <summary>
        /// Само значение стата. Для статов, которые игра сама обнуляет (счёт
        /// текущего заезда), или когда нужен порог, а не прирост.
        /// </summary>
        Absolute = 1
    }
}
