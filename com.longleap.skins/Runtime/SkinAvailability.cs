namespace LongLeap.Skins
{
    /// <summary>
    /// Как игрок получает скин. Одно поле вместо двух галок намеренно: «открыт
    /// с начала» и «надевается по умолчанию» не бывают в любых сочетаниях —
    /// нельзя надеть по умолчанию то, чего у игрока нет, — а два bool такую
    /// пару разрешили бы и тихо сломали бы вид персонажа.
    /// </summary>
    public enum SkinAvailability
    {
        /// <summary>
        /// Закрыт: выдаётся наградой или покупкой. Так живёт большинство скинов,
        /// поэтому это значение по умолчанию.
        /// </summary>
        Locked = 0,

        /// <summary>
        /// Открыт с самого начала И надет на новом игроке — стартовый набор: в обычной
        /// группе первый такой скин группы, в группе с множественным выбором все, и
        /// сразу в своём Default Color. В сейв не пишется: приходит из каталога при
        /// каждой загрузке, поэтому его нельзя потерять.
        /// </summary>
        OwnedFromStart = 1,

        /// <summary>
        /// Открыт с начала, но новичку не надевается. Первый такой в категории — её
        /// резерв: его надевают, когда надеть больше нечего (надетый скин перестал
        /// быть своим, а у группы нет своего Owned From Start).
        /// </summary>
        Default = 2,

        /// <summary>
        /// Временно отключён: в каталог не входит вовсе — в кастомизации его не видно,
        /// надеть и выдать его нельзя. У игроков, которым он уже выдан, запись в сейве
        /// остаётся: включат обратно — скин вернётся к ним сам.
        /// </summary>
        Disabled = 3
    }
}
