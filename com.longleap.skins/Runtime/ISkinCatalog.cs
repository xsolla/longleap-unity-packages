using System.Collections.Generic;
using UnityEngine;

namespace LongLeap.Skins
{
    /// <summary>
    /// Что вообще есть в игре: категории и скины в каждой из них. Это КОНТЕНТ,
    /// одинаковый у всех игроков, — а инвентарь отвечает на другой вопрос: что
    /// из этого открыто у конкретного игрока.
    ///
    /// Разделение важно для сейва: в него уходят только открытые скины, без
    /// категорий. Категория скина — данные каталога, и, пока она лежит в одном
    /// месте, скин можно перенести в другую вкладку правкой ассета, не трогая
    /// сейвы игроков.
    /// </summary>
    public interface ISkinCatalog
    {
        /// <summary>Категории в порядке каталога — в нём же их показывает UI.</summary>
        IReadOnlyList<SkinCategoryId> Categories { get; }

        /// <summary>
        /// Все скины категории в порядке каталога. Незнакомая категория — пустой
        /// список, а не исключение: вкладка просто окажется пустой.
        /// </summary>
        IReadOnlyList<SkinId> GetSkins(SkinCategoryId category);

        /// <summary>
        /// Заголовок категории для UI: HEAD, BODY, LEGS, BOARD. Пусто в каталоге —
        /// возвращается id категории заглавными: «head» → «HEAD».
        ///
        /// Это тоже контент: строки категорий UI создаёт по каталогу, одну на
        /// категорию, и написать подпись руками в префабе больше негде.
        /// </summary>
        string GetCategoryTitle(SkinCategoryId category);

        /// <summary>
        /// Подпись варианта для UI. Пусто в каталоге — возвращается имя скина:
        /// в спайне имена вида «board_neon» читаемы настолько, что на время
        /// разработки сойдут за подпись, и лишнее поле заполнять не нужно.
        /// </summary>
        string GetTitle(SkinId skin);

        /// <summary>
        /// Стартовый набор категории — скины <see cref="SkinAvailability.OwnedFromStart"/>
        /// в порядке каталога: в них одет новый игрок. Каталог отдаёт их все, а сколько
        /// надеть на группу (первый или все — у групп с множественным выбором), решает
        /// сервис надетого.
        /// </summary>
        IReadOnlyList<SkinId> GetStartingOutfit(SkinCategoryId category);

        /// <summary>
        /// Дефолтный скин категории — её резерв: он открыт у всех и всегда, и
        /// именно его надевают, когда надеть больше нечего (надетый скин перестал
        /// быть своим, а у группы нет своего стартового скина). Новичка одевают не
        /// в него, а в стартовый набор — см. <see cref="GetStartingOutfit"/>.
        ///
        /// Пусто только у категории, в которой вообще нет открытых с начала
        /// скинов, — то есть заполненной с ошибкой.
        /// </summary>
        SkinId GetDefault(SkinCategoryId category);

        /// <summary>Есть ли такой скин в каталоге вообще.</summary>
        bool Contains(SkinId skin);

        /// <summary>В какой категории лежит скин.</summary>
        bool TryGetCategory(SkinId skin, out SkinCategoryId category);

        /// <summary>
        /// Скин открыт всем и с самого начала — базовая доска, базовая голова.
        /// Такие скины не сохраняются: они приходят из каталога при каждой
        /// загрузке, поэтому их нельзя потерять и незачем выдавать.
        /// </summary>
        bool IsOwnedFromStart(SkinId skin);

        /// <summary>
        /// Скин есть в раскладке, но временно отключён (<see cref="SkinAvailability.Disabled"/>):
        /// в каталоге его нет, и <see cref="Contains"/> про него — false. Отдельный ответ
        /// нужен, чтобы выдача отключённого скина была штатным отказом, а не ошибкой
        /// «такого скина не существует».
        /// </summary>
        bool IsDisabled(SkinId skin);

        /// <summary>
        /// Зоны перекраса (SpineAppearanceConfig.ColorZone) для группы (папки скинов) —
        /// из раскладки. Пусто — у группы нет кнопки «color» вовсе, а не кнопка,
        /// которая ничего не делает.
        /// </summary>
        IReadOnlyList<string> GetGroupColorZones(string group);

        /// <summary>
        /// Можно ли у группы (папки скинов) не быть надетым вариантом вовсе. false —
        /// у группы всегда должен быть выбран ровно один вариант (базовая голова,
        /// доска), и повторное нажатие на уже надетый вариант ничего не снимает.
        /// Незнакомая группа — true: раскладка не запрещала, и запрещать не нам.
        /// </summary>
        bool CanGroupBeOff(string group);

        /// <summary>
        /// Можно ли надеть несколько вариантов группы (папки скинов) сразу —
        /// аксессуары. true — новый вариант добавляется к надетым, а не вытесняет
        /// прежний. Незнакомая группа — false: по умолчанию вариант в группе один.
        /// </summary>
        bool IsGroupMultiSelect(string group);

        /// <summary>
        /// Цвет по умолчанию для скина — красится сразу, как только игрок его выбирает
        /// (см. Skin Layout Editor, поле Default Color у скина). false — умолчания нет,
        /// зоны группы остаются такими, какими были.
        /// </summary>
        bool TryGetDefaultColor(SkinId skin, out Color color);

        /// <summary>
        /// Иконка скина для панели кастомизации — своя у каждого скина, не у группы
        /// и не у категории (см. Skin Layout Editor, поле иконки в строке скина).
        /// null — иконки нет, вариант покажется таким, каким лежит в шаблоне.
        /// </summary>
        Sprite GetIcon(SkinId skin);
    }
}
