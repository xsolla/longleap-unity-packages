namespace LongLeap.Core.Ads
{
    // Чем закончился показ рекламы.
    //
    // Намеренно нет отдельного Dismissed: порталы (в частности GamePix) сообщают
    // только успех или неуспех, и «игрок закрыл ролик» неотличимо от «рекламы нет».
    // Придумывать различие, которого нет в данных, значит врать вызывающему коду.
    public enum AdResult
    {
        // Ролик досмотрен до конца — только в этом случае можно выдавать награду.
        Completed,

        // Показ не состоялся или был прерван: закрыли, не загрузилось, таймаут.
        Failed,

        // Рекламы нет в принципе: не портальная сборка, провайдер-заглушка.
        Unavailable
    }
}
