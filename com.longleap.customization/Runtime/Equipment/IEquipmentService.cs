using System;
using System.Collections.Generic;
using LongLeap.Skins;

namespace LongLeap.Customization
{
    /// <summary>
    /// Что на игроке надето: по одному скину на папку Spine, а в группах с
    /// множественным выбором (аксессуары) — сколько угодно.
    ///
    /// Отдельно от инвентаря, потому что это разные вопросы с разной судьбой:
    /// «скин у меня есть» — навсегда, «скин на мне» — до следующего нажатия.
    /// Держать выбор внутри инвентаря значило бы, что панель кастомизации,
    /// игровая сцена и витрина выясняют текущий вид тремя разными способами.
    ///
    /// Новый игрок одет в стартовый набор — скины Owned From Start (Skin Layout Editor).
    ///
    /// Надетое чинится само: если скина не стало (чит-очистка, скин убрали из
    /// каталога), группа переодевается в свой стартовый скин или резерв категории —
    /// они открыты у игрока всегда, поэтому голым персонаж остаться не может.
    /// </summary>
    public interface IEquipmentService
    {
        /// <summary>
        /// Первый надетый скин категории. Для проверки конкретного варианта
        /// используй <see cref="IsEquipped"/>: в категории бывает несколько групп.
        /// </summary>
        SkinId GetEquipped(SkinCategoryId category);

        /// <summary>Надет ли конкретный скин.</summary>
        bool IsEquipped(SkinId skin);

        /// <summary>
        /// Весь текущий вид: надетое по всем категориям, без пустых.
        /// Ровно то, что уходит в <c>ISkinTarget.SetSkins</c>.
        ///
        /// Список пересобирается при каждом переодевании — если нужен потом,
        /// копируй.
        /// </summary>
        IReadOnlyList<SkinId> Outfit { get; }

        /// <summary>
        /// Надеть скин. false — скина нет в каталоге или он не открыт у игрока:
        /// надеть чужое нельзя, и это не исключение, а штатный ответ, потому что
        /// нажать на закрытый вариант игрок может и случайно.
        /// </summary>
        bool Equip(SkinId skin);

        /// <summary>
        /// Снять выбранный скин — только его: в группе с множественным выбором
        /// остальные варианты остаются надетыми. false — этот скин сейчас не надет
        /// или это последний вариант группы, которой нельзя быть пустой.
        /// </summary>
        bool Unequip(SkinId skin);

        /// <summary>
        /// В категории сменился скин: категория и то, что теперь на игроке
        /// (пусто — в категории не осталось открытых скинов).
        /// </summary>
        event Action<SkinCategoryId, SkinId> Changed;
    }
}
