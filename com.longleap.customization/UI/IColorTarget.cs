using UnityEngine;

namespace LongLeap.Customization
{
    /// <summary>
    /// Тот, кому палитра кастомизации красит зону — на деле спайновый персонаж.
    ///
    /// Аналог <see cref="ISkinTarget"/>, но для перекраса: панель и палитра знают
    /// ровно одно — «покрась зону вот в этот цвет». Что такое зона (список слотов
    /// скелета) и как цвет ложится на них — забота реализации
    /// (компонент хоста на скелете), поэтому сборка пакета
    /// собирается без спайнового рантайма и не ломается, пока его в проекте нет.
    ///
    /// Реализует его тот же компонент, что и <see cref="ISkinTarget"/> — зоны и
    /// скины красят один и тот же скелет.
    /// </summary>
    public interface IColorTarget
    {
        /// <summary>
        /// Перекрасить зону. false — зоны с таким именем у этого скелета нет: это
        /// штатный ответ, а не ошибка, потому что набор зон живёт в инспекторе
        /// художника и не обязан совпадать с именами групп скинов.
        /// </summary>
        bool SetZoneColor(string zone, Color color);

        /// <summary>
        /// Перекрасить одну вещь: только те слоты скина, что входят в зоны перекраса,
        /// поверх цвета зоны. Нужно группам с множественным выбором (аксессуары) —
        /// зона у их вещей общая, а цвет у каждой свой. Цвет действует, пока скин
        /// надет, и запоминается до следующего раза. false — такого скина в скелете нет.
        /// </summary>
        bool SetSkinColor(string skin, Color color);
    }
}
