namespace LongLeap.Customization
{
    /// <summary>
    /// Поза персонажа-превью в кастомизации: панель сообщает, с какой группой скинов
    /// (Hair, Skateboard Grip…) игрок сейчас работает, а персонаж сам решает, как ему
    /// встать, чтобы эту часть было видно — например, перевернуть доску, когда
    /// выбирают грип: сверху доски его не разглядеть.
    ///
    /// Аналог <see cref="ISkinTarget"/> и <see cref="IColorTarget"/>: панель не знает
    /// ни аниматора, ни имён его параметров, ни того, каким группам нужна особая поза,
    /// — это настраивается на самом персонаже (компонент хоста).
    /// Персонажа без такого компонента панель просто не поворачивает.
    /// </summary>
    public interface IPreviewPose
    {
        /// <summary>
        /// Игрок перешёл к группе <paramref name="group"/> — выбрал в ней вариант или
        /// открыл её палитру. <c>null</c> — ни к какой: сменил категорию или закрыл
        /// панель, персонаж возвращается в обычную позу.
        /// </summary>
        void Focus(string group);
    }
}
